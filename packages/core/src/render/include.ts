/* include/c64-hardware.asm: every known symbol as `.label NAME = $xxxx // description` (Kick Assembler) or
 * `NAME = $xxxx ; description` (64tass) */
import type { Settings } from '../types';
import { SYM } from '../c64/symbols';
import { h4 } from '../util/hex';
import { ASSEMBLERS, assemblerOf } from './dialect';

interface IncludeSym { name: string; addr: number; desc: string }

export function hardwareInclude(S: Pick<Settings, 'hexCase'> & Partial<Pick<Settings, 'assembler'>>): string {
  const asm = assemblerOf(S), cm = ASSEMBLERS[asm].comment;
  const out = [`${cm} C64 hardware, KERNAL and system symbols`, `${cm} generated by Mimir Studio for ${ASSEMBLERS[asm].title}`, ''];
  const cats = new Map<string, IncludeSym[]>();
  for (const s of SYM.exact.values()) { if (/\+/.test(s.name)) continue; if (!cats.has(s.cat)) cats.set(s.cat, []); cats.get(s.cat)!.push(s); }
  for (const r of SYM.regions) { if (!cats.has(r.cat)) cats.set(r.cat, []); cats.get(r.cat)!.push({ name: r.name, addr: r.start, desc: r.desc }); }
  for (const [cat, list] of cats) {
    out.push(`${cm} ---- ${cat} ----`);
    for (const s of list.sort((x, y) => x.addr - y.addr)) {
      const value = `$${S.hexCase === 'upper' ? h4(s.addr).toUpperCase() : h4(s.addr)}`;
      const left = asm === '64tass' ? `${s.name.padEnd(24)} = ${value}` : `.label ${s.name.padEnd(18)} = ${value}`;
      out.push(`${left.padEnd(36)}${cm} ${s.desc}`);
    }
    out.push('');
  }
  return out.join('\n');
}
